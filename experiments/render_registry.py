"""Render experiments/*.csv into the README between registry markers, and fill Wilson intervals."""

import argparse
import csv
import math
from pathlib import Path

EXPERIMENTS_DIR = Path(__file__).resolve().parent
MODELS_CSV = EXPERIMENTS_DIR / "models.csv"
RESULTS_CSV = EXPERIMENTS_DIR / "results.csv"
SOURCES_CSV = EXPERIMENTS_DIR / "sources.csv"
README = EXPERIMENTS_DIR.parent / "README.md"

START = "<!-- registry:start -->"
END = "<!-- registry:end -->"

Z_95 = 1.959963985

# Metrics whose value is a proportion in [0, 1] and therefore gets a Wilson interval from n.
PROPORTION_METRICS = {
    "accuracy",
    "parse_rate",
    "verified_success_rate",
    "verified_success_rate_audited",
    "canonical_form_rate",
    "parse_failure_rate",
    "ddr",
    "done_rate",
    "oracle_success_rate",
    "false_done_rate",
    "ui_coverage_views",
    "ui_coverage_elements",
    "flakiness",
    "post_login_share",
    "pass_rate_retained",
    "phase_call_share",
    "phase_cost_share",
    "post_login_work_share",
}

MODEL_COLUMNS = ["model_id", "kind", "base_model", "dataset_version", "method", "status", "notes"]
SOURCE_COLUMNS = ["claim", "value", "n", "venue", "year", "reference", "used_on"]
RESULT_COLUMNS = ["model_id", "subset", "metric", "value", "n", "artifacts_availability", "status", "notes"]
STATUS_ORDER = {"done": 0, "pending": 1, "running": 2, "planned": 3, "failed": 4, "superseded": 5}


def read_csv(path):
    with path.open(encoding="utf8", newline="") as handle:
        reader = csv.DictReader(handle)
        return list(reader), reader.fieldnames


def write_csv(path, rows, fieldnames):
    with path.open("w", encoding="utf8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def wilson(successes_fraction, sample_size, z=Z_95):
    denominator = 1 + z * z / sample_size
    centre = (successes_fraction + z * z / (2 * sample_size)) / denominator
    margin = (
        z
        * math.sqrt(
            successes_fraction * (1 - successes_fraction) / sample_size + z * z / (4 * sample_size * sample_size)
        )
        / denominator
    )
    return max(0.0, centre - margin), min(1.0, centre + margin)


def fill_intervals(rows):
    filled = 0
    for row in rows:
        if row["metric"] not in PROPORTION_METRICS or not row["value"] or not row["n"]:
            continue
        if row["ci_low"] and row["ci_high"]:
            continue
        value, sample_size = float(row["value"]), int(row["n"])
        if sample_size < 2:
            continue
        low, high = wilson(value, sample_size)
        row["ci_low"], row["ci_high"] = f"{low:.4f}", f"{high:.4f}"
        filled += 1
    return filled


def format_value(row):
    if not row["value"]:
        return "_not measured_"
    if row["metric"] in PROPORTION_METRICS:
        text = f"{float(row['value']) * 100:.1f} %"
        if row["ci_low"] and row["ci_high"]:
            text += f" <sub>[{float(row['ci_low']) * 100:.0f}–{float(row['ci_high']) * 100:.0f}]</sub>"
        return text
    if row["metric"].endswith("_usd"):
        return f"${float(row['value']):.2f}"
    number = float(row["value"])
    return str(int(number)) if number.is_integer() else f"{number:g}"


def table(rows, columns, formatter=None):
    lines = ["| " + " | ".join(columns) + " |", "| " + " | ".join("---" for _ in columns) + " |"]
    for row in rows:
        cells = [(formatter(row, column) if formatter else row.get(column, "")) or "" for column in columns]
        lines.append("| " + " | ".join(cell.replace("|", "\\|") for cell in cells) + " |")
    return lines


def result_cell(row, column):
    return format_value(row) if column == "value" else row.get(column, "")


def sort_key(row):
    return STATUS_ORDER.get(row["status"], 9), row["model_id"], row["subset"], row["metric"]


def source_cell(row, column):
    return f"{float(row['value']) * 100:.1f} %" if column == "value" and row["value"] else row.get(column, "")


def render(models, results, sources):
    lines = [START, "", "<!-- generated by experiments/render_registry.py; edit the CSVs, not this block -->", ""]
    lines += ["### Models and training runs", ""]
    lines += table(models, MODEL_COLUMNS)
    lines += ["", "### Results", ""]
    for eval_name in sorted({row["eval_name"] for row in results}):
        subset = sorted([row for row in results if row["eval_name"] == eval_name], key=sort_key)
        version = sorted({row["eval_version"] for row in subset if row["eval_version"]})
        lines += [f"#### `{eval_name}`" + (f" — {', '.join(version)}" if version else ""), ""]
        lines += table(subset, RESULT_COLUMNS, result_cell)
        lines += [""]
    lines += ["### Figures cited from other people's studies", ""]
    lines += table(sources, SOURCE_COLUMNS, source_cell)
    lines += [""]
    counts = {}
    for row in results:
        counts[row["status"]] = counts.get(row["status"], 0) + 1
    tally = ", ".join(
        f"{count} {status}" for status, count in sorted(counts.items(), key=lambda kv: STATUS_ORDER.get(kv[0], 9))
    )
    lines += [
        f"_{len(results)} registry rows: {tally}. Percentages carry a 95 % Wilson interval where n is known._",
        "",
        END,
    ]
    return "\n".join(lines)


def splice(readme_text, block):
    if START not in readme_text or END not in readme_text:
        raise SystemExit(f"markers {START} / {END} not found in {README}")
    head = readme_text.split(START)[0]
    tail = readme_text.split(END)[1]
    return head + block + tail


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--fill-ci", action="store_true", help="compute missing Wilson intervals and rewrite results.csv"
    )
    parser.add_argument("--check", action="store_true", help="exit 1 if the README block is stale")
    args = parser.parse_args()

    models, model_fields = read_csv(MODELS_CSV)
    results, result_fields = read_csv(RESULTS_CSV)
    sources, _ = read_csv(SOURCES_CSV)

    if args.fill_ci:
        filled = fill_intervals(results)
        write_csv(RESULTS_CSV, results, result_fields)
        print(f"filled {filled} interval(s) in {RESULTS_CSV.name}")

    block = render(models, results, sources)
    readme_text = README.read_text(encoding="utf8")
    updated = splice(readme_text, block)
    if args.check:
        if updated != readme_text:
            raise SystemExit("README registry block is stale; run experiments/render_registry.py")
        print("README registry block is up to date")
        return
    README.write_text(updated, encoding="utf8")
    print(f"rendered {len(models)} model(s) and {len(results)} result(s) into {README.name}")


if __name__ == "__main__":
    main()
